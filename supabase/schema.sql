-- Every shared player appears for every game, including players with zero wins.
drop view if exists public.game_leaderboard_view;
create view public.game_leaderboard_view as
select
  games.id as board_game_id,
  players.id as player_id,
  players.name,
  count(winners.id)::integer as wins
from public.boardgames as games
cross join public.players
left join public.game_sessions as sessions
  on sessions.board_game_id = games.id
left join public.session_participants as winners
  on winners.session_id = sessions.id
  and winners.player_id = players.id
  and winners.is_winner = true
where players.name is not null
  and btrim(players.name) <> ''
group by games.id, players.id, players.name;

