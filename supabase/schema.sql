create or replace function public.add_player(p_name text)
returns table (id bigint, name text)
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized_name text := btrim(p_name);
begin
  if p_name is null or normalized_name = '' then
    raise exception 'Player name cannot be empty';
  end if;

  insert into public.players (name)
  values (normalized_name)
  on conflict do nothing;

  return query
  select players.id, players.name
  from public.players
  where lower(btrim(players.name)) = lower(normalized_name)
  order by players.id
  limit 1;
end;
$$;

create or replace function public.record_player_win(
  p_board_game_id bigint,
  p_player_id bigint
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  new_session_id bigint;
begin
  if not exists (select 1 from public.boardgames where id = p_board_game_id) then
    raise exception 'The requested board game does not exist';
  end if;
  if not exists (select 1 from public.players where id = p_player_id) then
    raise exception 'The requested player does not exist';
  end if;

  insert into public.game_sessions (board_game_id)
  values (p_board_game_id)
  returning id into new_session_id;

  insert into public.session_participants (session_id, player_id, is_winner)
  values (new_session_id, p_player_id, true);
end;
$$;

create or replace function public.remove_player_win(
  p_board_game_id bigint,
  p_player_id bigint
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  session_to_remove bigint;
begin
  select sessions.id
  into session_to_remove
  from public.game_sessions as sessions
  join public.session_participants as participants
    on participants.session_id = sessions.id
  where sessions.board_game_id = p_board_game_id
    and participants.player_id = p_player_id
    and participants.is_winner = true
  order by sessions.played_at desc, sessions.id desc
  limit 1;

  if session_to_remove is null then
    raise exception 'No recorded win exists for this player and game';
  end if;

  delete from public.session_participants
  where session_id = session_to_remove
    and player_id = p_player_id
    and is_winner = true;

  delete from public.game_sessions
  where id = session_to_remove
    and not exists (
      select 1 from public.session_participants
      where session_id = session_to_remove
    );
end;
$$;

