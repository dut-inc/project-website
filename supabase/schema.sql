-- Existing databases may have created this table before the unique constraint
-- was added. Merge duplicates first, then add the constraint idempotently so
-- the later player-deduplication migration can safely use ON CONFLICT.
update public.session_participants as target
set is_winner = true
from public.session_participants as source
where target.session_id = source.session_id
  and target.player_id = source.player_id
  and source.is_winner = true
  and target.is_winner = false;

with duplicate_participants as (
  select
    id,
    row_number() over (
      partition by session_id, player_id
      order by id asc
    ) as row_number
  from public.session_participants
)
delete from public.session_participants as participants
using duplicate_participants
where participants.id = duplicate_participants.id
  and duplicate_participants.row_number > 1;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conrelid = 'public.session_participants'::regclass
      and conname = 'session_participants_session_player_key'
  ) then
    alter table public.session_participants
      add constraint session_participants_session_player_key
      unique (session_id, player_id);
  end if;
end
$$;

-- Import names from the old leaderboard table into the shared player list.
insert into public.players (name)
select legacy.name
from (
  select distinct on (lower(btrim(name))) btrim(name) as name
  from public.game_leaderboard
  where name is not null and btrim(name) <> ''
  order by lower(btrim(name)), wins desc, id asc
) as legacy
where not exists (
  select 1
  from public.players
  where lower(btrim(players.name)) = lower(legacy.name)
);

-- Merge case/spacing duplicate players without losing participant history.
with ranked_players as (
  select
    id,
    first_value(id) over (
      partition by lower(btrim(name))
      order by id asc
    ) as canonical_id,
    row_number() over (
      partition by lower(btrim(name))
      order by id asc
    ) as row_number
  from public.players
  where name is not null
), duplicate_players as (
  select id, canonical_id from ranked_players where row_number > 1
)
insert into public.session_participants (session_id, player_id, is_winner)
select
  participants.session_id,
  duplicate_players.canonical_id,
  bool_or(participants.is_winner)
from duplicate_players
join public.session_participants as participants
  on participants.player_id = duplicate_players.id
group by participants.session_id, duplicate_players.canonical_id
on conflict (session_id, player_id) do update
set is_winner = public.session_participants.is_winner or excluded.is_winner;

