-- Convert old manually edited scores into real win sessions. Existing session
-- wins are preserved; only the missing difference is materialized.
create table if not exists public.scorebook_migrations (
  key text primary key,
  applied_at timestamptz not null default now()
);

do $$
declare
  legacy_entry record;
  new_session_id bigint;
  counter integer;
begin
  if not exists (
    select 1 from public.scorebook_migrations where key = 'leaderboard-to-sessions'
  ) then
    for legacy_entry in
      select
        legacy_scores.board_game_id,
        players.id as player_id,
        greatest(
          legacy_scores.legacy_wins - coalesce(existing_wins.win_count, 0),
          0
        )::integer as missing_wins
      from (
        select
          board_game_id,
          lower(btrim(name)) as normalized_name,
          sum(wins)::integer as legacy_wins
        from public.game_leaderboard
        group by board_game_id, lower(btrim(name))
      ) as legacy_scores
      join public.players
        on lower(btrim(players.name)) = legacy_scores.normalized_name
      left join (
        select
          sessions.board_game_id,
          participants.player_id,
          count(*)::integer as win_count
        from public.game_sessions as sessions
        join public.session_participants as participants
          on participants.session_id = sessions.id
        where participants.is_winner = true
        group by sessions.board_game_id, participants.player_id
      ) as existing_wins
        on existing_wins.board_game_id = legacy_scores.board_game_id
        and existing_wins.player_id = players.id
      where legacy_scores.legacy_wins > coalesce(existing_wins.win_count, 0)
    loop
      for counter in 1..legacy_entry.missing_wins loop
        insert into public.game_sessions (board_game_id)
        values (legacy_entry.board_game_id)
        returning id into new_session_id;

        insert into public.session_participants (session_id, player_id, is_winner)
        values (new_session_id, legacy_entry.player_id, true);
      end loop;
    end loop;

    insert into public.scorebook_migrations (key)
    values ('leaderboard-to-sessions');
  end if;
end;
$$;

