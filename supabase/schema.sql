-- Board-game table used by /db-management.
-- Run this in the Supabase SQL editor before using the prototype page.

create table if not exists public.boardgames (
  id bigint generated by default as identity not null,
  created_at timestamptz not null default now(),
  name text null default '',
  tier text null default 'Unranked',
  description text null,
  house_rules text null,
  quick_notes text null,
  full_rules text null,
  constraint boardgames_pkey primary key (id)
);

alter table public.boardgames enable row level security;

-- The public browser client uses the anon role when no user is signed in.
-- Authenticated sessions use the authenticated role. These grants are needed
-- in addition to RLS policies for PostgREST table access.
grant select, insert, update, delete on table public.boardgames to anon, authenticated;

do $$
declare
  identity_sequence regclass;
begin
  identity_sequence := pg_get_serial_sequence('public.boardgames', 'id');

  if identity_sequence is not null then
    execute format(
      'grant usage, select on sequence %s to anon, authenticated',
      identity_sequence
    );
  end if;
end
$$;

-- Prototype-only policies. Replace these with authenticated, owner-scoped
-- policies before production use; the page itself displays a warning.
drop policy if exists "prototype board games are readable" on public.boardgames;
drop policy if exists "prototype board games are insertable" on public.boardgames;
drop policy if exists "prototype board games are editable" on public.boardgames;
drop policy if exists "prototype board games are removable" on public.boardgames;

create policy "prototype board games are readable"
  on public.boardgames for select
  to anon, authenticated
  using (true);

create policy "prototype board games are insertable"
  on public.boardgames for insert
  to anon, authenticated
  with check (true);

create policy "prototype board games are editable"
  on public.boardgames for update
  to anon, authenticated
  using (true)
  with check (true);

create policy "prototype board games are removable"
  on public.boardgames for delete
  to anon, authenticated
  using (true);
